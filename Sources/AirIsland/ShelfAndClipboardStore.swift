import Cocoa
import SwiftUI
import UniformTypeIdentifiers

struct ShelfFileItem: Identifiable, Equatable {
    let id = UUID()
    let url: URL
    let name: String
    let icon: NSImage

    static func == (lhs: ShelfFileItem, rhs: ShelfFileItem) -> Bool {
        lhs.url == rhs.url
    }
}

struct ClipboardEntry: Identifiable, Equatable {
    let id = UUID()
    let text: String
    let date: Date
}

final class ShelfAndClipboardStore: ObservableObject {
    @Published var files: [ShelfFileItem] = []
    @Published var clipboardHistory: [ClipboardEntry] = []

    private var lastChangeCount: Int
    private var pollTimer: Timer?
    private let maxClipboardItems = 15

    var onFileAdded: ((String) -> Void)?

    init() {
        self.lastChangeCount = NSPasteboard.general.changeCount
        captureCurrentPasteboardIfText()
        pollTimer = Timer.scheduledTimer(withTimeInterval: 1.5, repeats: true) { [weak self] _ in
            self?.checkPasteboard()
        }
    }

    deinit {
        pollTimer?.invalidate()
    }

    // MARK: - File Shelf

    func addFile(url: URL) {
        let standardized = url.standardizedFileURL
        guard FileManager.default.fileExists(atPath: standardized.path) else { return }
        if files.contains(where: { $0.url == standardized }) {
            return
        }
        let icon = NSWorkspace.shared.icon(forFile: standardized.path)
        icon.size = NSSize(width: 32, height: 32)
        let item = ShelfFileItem(
            url: standardized,
            name: standardized.lastPathComponent,
            icon: icon
        )
        files.insert(item, at: 0)
        onFileAdded?(item.name)
    }

    func removeFile(_ item: ShelfFileItem) {
        files.removeAll { $0.id == item.id }
    }

    func clearFiles() {
        files.removeAll()
    }

    func openFile(_ item: ShelfFileItem) {
        NSWorkspace.shared.open(item.url)
    }

    func revealInFinder(_ item: ShelfFileItem) {
        NSWorkspace.shared.activateFileViewerSelecting([item.url])
    }

    func airDropFile(_ item: ShelfFileItem) {
        if let service = NSSharingService(named: .sendViaAirDrop) {
            if service.canPerform(withItems: [item.url]) {
                service.perform(withItems: [item.url])
            }
        }
    }

    func handleDrop(providers: [NSItemProvider]) -> Bool {
        var accepted = false
        let typeId = UTType.fileURL.identifier
        for provider in providers where provider.hasItemConformingToTypeIdentifier(typeId) {
            accepted = true
            provider.loadItem(forTypeIdentifier: typeId, options: nil) { [weak self] item, _ in
                var resolvedURL: URL?
                if let data = item as? Data {
                    resolvedURL = URL(dataRepresentation: data, relativeTo: nil)
                } else if let url = item as? URL {
                    resolvedURL = url
                } else if let str = item as? String {
                    resolvedURL = URL(string: str)
                }
                if let url = resolvedURL {
                    DispatchQueue.main.async {
                        self?.addFile(url: url)
                    }
                }
            }
        }
        return accepted
    }

    // MARK: - Clipboard History

    private func checkPasteboard() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChangeCount else { return }
        lastChangeCount = pb.changeCount
        captureCurrentPasteboardIfText()
    }

    private func captureCurrentPasteboardIfText() {
        let pb = NSPasteboard.general
        // Respect concealed/transient password manager pasteboard markers
        let types = pb.types ?? []
        let ignoredMarkers: Set<String> = [
            "org.nspasteboard.ConcealedType",
            "org.nspasteboard.TransientType",
            "org.nspasteboard.AutoGeneratedType"
        ]
        if types.contains(where: { ignoredMarkers.contains($0.rawValue) }) {
            return
        }

        guard let raw = pb.string(forType: .string) else { return }
        let trimmed = raw.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else { return }

        if clipboardHistory.first?.text == raw {
            return
        }
        clipboardHistory.removeAll { $0.text == raw }
        clipboardHistory.insert(ClipboardEntry(text: raw, date: Date()), at: 0)
        if clipboardHistory.count > maxClipboardItems {
            clipboardHistory = Array(clipboardHistory.prefix(maxClipboardItems))
        }
    }

    func copyToPasteboard(_ entry: ClipboardEntry) {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(entry.text, forType: .string)
        lastChangeCount = pb.changeCount
        clipboardHistory.removeAll { $0.id == entry.id }
        clipboardHistory.insert(ClipboardEntry(text: entry.text, date: Date()), at: 0)
    }

    func clearClipboard() {
        clipboardHistory.removeAll()
    }
}
